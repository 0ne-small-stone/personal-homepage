// Run with an independently supplied Playwright package; no website dependency.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { createRequire } = require('node:module');
const { chromium } = createRequire(process.env.PLAYWRIGHT_PACKAGE)('playwright');
const base = process.argv[2] ?? 'http://127.0.0.1:4366/personal-homepage';
const output = path.resolve(process.argv[3] ?? '.ci-tmp/t06-01-browser');
const title = 'PDF 阅读验证说明（功能样本）';
const detail = `${base}/knowledge/resources/reading-guide/`;
const file = `${base}/materials/lssh-pdf-reading-check.pdf`;
const expectedHash = '9e2aac37f32cc56aff3a15434a525659c95096d4481c8739c7ee9471fca953be';
const checks = [];
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const record = (name, data = {}) => checks.push({ name, result: 'passed', ...data });
const rendered = async (frame) => {
  await frame.waitForFunction(() => {
    const app = window.PDFViewerApplication;
    const view = app?.pdfViewer?.getPageView(app.pdfViewer.currentPageNumber - 1);
    const canvas = view?.div.querySelector('canvas');
    if (view?.renderingState !== 3 || !canvas?.width || !canvas?.height) return false;
    const pixels = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
    let ink = 0;
    for (let i = 0; i < pixels.length; i += 64) if (pixels[i] < 180 && pixels[i + 3] > 0) ink++;
    return ink > 50;
  });
};
const ready = async (page) => {
  await page.locator('pdf-reader[aria-busy="false"] iframe').waitFor({ timeout: 45000 });
  const frame = page.frames().find((frame) => frame.url().includes('/pdfjs/web/viewer.html'));
  assert(frame, 'Missing PDF viewer');
  await frame.waitForFunction(() => window.PDFViewerApplication?.isInitialViewSet && window.PDFViewerApplication?.pdfDocument, null, { timeout: 45000 });
  await frame.locator('canvas').first().waitFor();
  assert.equal(await frame.evaluate(() => window.PDFViewerApplication.pdfDocument.numPages), 4);
  return frame;
};
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN', acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const response = await page.request.get(file);
  assert.equal(response.status(), 200);
  const bytes = await response.body();
  assert.equal(bytes.byteLength, 65959);
  assert.equal(hash(bytes), expectedHash);
  record('clean-preview HTTP attachment and checksum', { bytes: bytes.length, sha256: hash(bytes) });

  await page.goto(`${base}/knowledge/?type=resource&topic=${encodeURIComponent('阅读与整理')}`);
  assert.equal(await page.locator('.knowledge-list > li:not([hidden])').count(), 1);
  const link = page.locator('.knowledge-list').getByRole('link', { name: title, exact: true });
  assert((await link.locator('..').textContent()).includes('演示内容'));
  await link.click();
  let frame = await ready(page);
  assert.equal(page.url(), detail);
  assert((await page.locator('[data-status]').textContent()).includes('共 4 页'));
  assert(!(await page.locator('iframe').getAttribute('src')).includes('local-materials'));
  record('filtered overview opens directly rendered sample');
  await page.locator('.source-details summary').click();
  const info = await page.locator('.source-details').textContent();
  assert(info.includes('65,959') && info.includes('4 页') && info.includes('CC0-1.0') && info.includes('功能样本'));
  record('visible source, license and metadata');
  await page.locator('.source-details summary').click();
  await frame.locator('#pageNumber').fill('3');
  await frame.locator('#pageNumber').press('Enter');
  await frame.locator('#scaleSelect').selectOption('1.25');
  await frame.waitForFunction(() => window.PDFViewerApplication.pdfViewer.currentPageNumber === 3 && window.PDFViewerApplication.pdfViewer.currentScale === 1.25);
  await frame.locator('.page[data-page-number="3"] canvas').waitFor();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('pdfjs.history') ?? '{}').files?.some((item) => item.page === 3 && Number(item.zoom) === 125));
  await page.reload();
  frame = await ready(page);
  assert.deepEqual(await frame.evaluate(() => ({ page: window.PDFViewerApplication.pdfViewer.currentPageNumber, scale: window.PDFViewerApplication.pdfViewer.currentScale })), { page: 3, scale: 1.25 });
  record('page 3 and 125% survive refresh');
  await page.locator('[data-article-return]').click();
  await page.waitForURL(`${base}/knowledge/?type=resource&topic=${encodeURIComponent('阅读与整理')}`);
  await page.waitForFunction(() => document.activeElement?.closest('.knowledge-list') !== null);
  assert((await page.evaluate(() => document.activeElement.textContent)).includes(title));
  record('return preserves type, topic and original list focus');
  await page.locator('.knowledge-list').getByRole('link', { name: title, exact: true }).click();
  frame = await ready(page);
  assert.equal(await frame.locator('#pageNumber').inputValue(), '3');
  record('reading position survives list round trip');

  await frame.locator('#viewFindButton').click();
  await frame.locator('#findInput').fill('阅读验证');
  await frame.locator('#findInput').press('Enter');
  await frame.waitForFunction(() => window.PDFViewerApplication.findController?.pageMatches?.flat().length > 0);
  const matches = await frame.evaluate(() => window.PDFViewerApplication.findController.pageMatches.map((items) => items.length));
  record('native Chinese search finds real text', { matches });
  await frame.locator('#viewFindButton').click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载 PDF', exact: true }).click();
  const download = await downloadPromise;
  const downloaded = fs.readFileSync(await download.path());
  assert.equal(hash(downloaded), expectedHash);
  record('download contains identical PDF bytes', { suggestedFilename: download.suggestedFilename() });
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('link', { name: '全屏阅读', exact: true }).click();
  const popup = await popupPromise;
  await popup.waitForFunction(() => window.PDFViewerApplication?.pdfDocument?.numPages === 4, null, { timeout: 45000 });
  assert.equal(new URL(popup.url()).searchParams.get('file'), '/personal-homepage/materials/lssh-pdf-reading-check.pdf');
  record('full reader opens same-origin attachment');
  await popup.close();

  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await rendered(frame);
  await page.screenshot({ path: path.join(output, 'desktop-dark.png'), fullPage: true });
  await page.evaluate(() => document.documentElement.dataset.theme = 'light');
  await frame.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await rendered(frame);
  await page.screenshot({ path: path.join(output, 'desktop-light.png'), fullPage: true });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    for (const control of await page.locator('.reader-actions a').all()) assert((await control.boundingBox()).height >= 44);
    record(`mobile ${width}px fits outer page and actions`);
  }
  await frame.evaluate(() => window.PDFViewerApplication.pdfViewer.currentScaleValue = 'page-width');
  await rendered(frame);
  await page.screenshot({ path: path.join(output, 'mobile-320.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('link', { name: '全屏阅读', exact: true }).focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('link', { name: '下载 PDF', exact: true }).evaluate((node) => node === document.activeElement), true);
  assert.equal(await page.getByRole('link', { name: '下载 PDF', exact: true }).evaluate((node) => getComputedStyle(node).outlineStyle), 'solid');
  record('download keyboard focus remains visible');
  assert.deepEqual(errors, []);
  record('no page script errors in normal reading', { errors });

  const failure = await context.newPage();
  await failure.route('**/materials/lssh-pdf-reading-check.pdf', (route) => route.fulfill({ status: 404, body: 'missing' }));
  await failure.goto(detail);
  await failure.locator('[data-error]:not([hidden])').waitFor({ timeout: 45000 });
  assert((await failure.locator('[data-status]').textContent()).includes('加载失败'));
  assert(await failure.getByRole('link', { name: '下载 PDF', exact: true }).isVisible());
  await failure.unroute('**/materials/lssh-pdf-reading-check.pdf');
  await failure.getByRole('button', { name: '重新加载' }).click();
  await ready(failure);
  assert(await failure.locator('[data-error]').getAttribute('hidden') !== null);
  record('failed PDF shows fallback and retry recovers');
  await failure.close();

  await page.goto(`${base}/knowledge/notes/ads/ads-algorithms-notes/`);
  assert.equal(await page.locator('pdf-reader iframe').count(), 0);
  assert((await page.locator('[data-status]').textContent()).includes('尚未接入'));
  record('clean build leaves private PDF unavailable truthfully');
  const local = await context.newPage();
  await local.goto('http://127.0.0.1:4322/personal-homepage/knowledge/notes/ads/ads-algorithms-notes/');
  const localFrame = local.frames().find((frame) => frame.url().includes('/pdfjs/web/viewer.html'));
  assert(localFrame);
  await localFrame.waitForFunction(() => window.PDFViewerApplication?.pdfDocument?.numPages === 35, null, { timeout: 45000 });
  assert((await local.locator('pdf-reader iframe').getAttribute('src')).includes('local-materials'));
  record('existing local 35-page note still renders on 4322');
  await local.close();
  const noJS = await browser.newContext({ javaScriptEnabled: false });
  const native = await noJS.newPage();
  await native.goto(detail);
  const fallback = native.locator('noscript a');
  assert.equal(await fallback.getAttribute('href'), '/personal-homepage/materials/lssh-pdf-reading-check.pdf');
  assert(await fallback.isVisible());
  record('no JavaScript has directly accessible PDF fallback');
  await noJS.close();
  await context.close();
  await browser.close();
  const report = { base, browser: 'Edge headless', result: 'passed', groups: checks.length, checks };
  fs.writeFileSync(path.join(output, 'browser.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
})().catch((error) => { console.error(error); process.exit(1); });
