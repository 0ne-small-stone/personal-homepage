const { chromium } = require(process.env.LSSH_QA_PLAYWRIGHT || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve('docs/design/iterations/evidence/u12-p13-2026-10-11-01', process.env.LSSH_QA_PHASE || 'initial');
fs.mkdirSync(root, { recursive: true });
if (fs.existsSync(path.join(root, 'checks.json'))) throw new Error('保留原始结果，使用新 LSSH_QA_PHASE 继续。');
const report = { date: new Date().toISOString(), checks: [], errors: [], limitations: ['Emulated viewports; cloud sharing and real-device performance are separate checks.'] };
function check(name, passed, details) { report.checks.push({ name, passed: !!passed, details }); console.log(`${name}: ${passed}`); }
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.LSSH_QA_BROWSER, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => report.errors.push(error.message));
  await page.goto('http://127.0.0.1:4321/personal-homepage/music/', { waitUntil: 'networkidle' });
  await page.waitForSelector('.radio-track');
  check('realLibrary', await page.locator('.radio-track').count() === 18, await page.locator('.radio-toolbar').innerText());
  check('cloudNotFalselyPlayable', await page.locator('audio').count() === 0 && await page.getByRole('button', { name: '播放待连接' }).isDisabled());
  check('lazyNetease', await page.locator('iframe').count() === 0);
  await page.screenshot({ path: path.join(root, 'desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '专辑', exact: true }).click();
  check('albums', await page.locator('.radio-album-list li').count() === 3);
  await page.locator('.radio-album-list button').filter({ hasText: '劳动之余' }).click();
  check('albumSongs', await page.locator('.radio-track').count() === 7);
  await page.getByRole('button', { name: '查看全部单曲' }).click();
  await page.getByRole('searchbox', { name: '查找歌曲、歌手或专辑' }).fill('抚琴');
  check('search', await page.locator('.radio-track').count() === 1);
  await page.locator('.radio-track').click();
  check('selection', await page.locator('.radio-now h2').innerText() === '抚琴小夜曲');
  await page.getByRole('searchbox').fill('不存在的测试曲目');
  check('emptySearch', await page.locator('.radio-track').count() === 0 && await page.locator('.radio-empty-result').isVisible());
  await page.getByRole('searchbox').fill('');
  await page.getByRole('button', { name: '刷新目录', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.radio-notice')?.textContent.includes('已刷新'));
  check('refresh', await page.locator('.radio-track').count() === 18);
  const lx = await page.getByRole('link', { name: '在洛雪中打开' }).getAttribute('href');
  check('officialLxProtocol', lx.startsWith('lxmusic://music/search?data=') && JSON.parse(decodeURIComponent(lx.split('data=')[1])).keywords.includes('抚琴'));
  check('directDownloadEntry', (await page.getByRole('link', { name: '下载音乐（打开洛雪）', exact: true }).getAttribute('href')).startsWith('lxmusic://music/search?data='));
  const realCatalog = await (await page.request.get('http://127.0.0.1:4321/personal-homepage/music/catalog.json')).json();
  await page.route('**/music/catalog.json', route => route.fulfill({ contentType: 'application/json', body: '{"version":99,"tracks":[]}' }));
  await page.getByRole('button', { name: '刷新目录', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.radio-notice')?.textContent.includes('保留上次'));
  check('invalidCatalogKeepsLastLibrary', await page.locator('.radio-track').count() === 18);
  await page.unroute('**/music/catalog.json');
  await page.route('**/music/catalog.json', route => route.fulfill({ contentType: 'application/json', body: '{"version":1,"updatedAt":null,"tracks":[]}' }));
  await page.getByRole('button', { name: '刷新目录', exact: true }).click();
  await page.waitForSelector('.radio-empty');
  check('emptyCatalogState', await page.locator('.radio-track').count() === 0 && await page.getByRole('button', { name: '播放待连接' }).isDisabled());
  await page.unroute('**/music/catalog.json');
  // Mock only the catalog and unavailable audio in this isolated browser context.
  const mocked = structuredClone(realCatalog);
  mocked.tracks[0].audioUrl = 'https://radio-fixture.invalid/unavailable.flac';
  await page.route('**/music/catalog.json', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(mocked) }));
  await page.route('https://radio-fixture.invalid/**', route => route.abort());
  await page.getByRole('button', { name: '刷新目录', exact: true }).click();
  await page.waitForSelector('audio');
  await page.locator('audio').evaluate(element => element.play().catch(() => {}));
  await page.waitForSelector('.radio-error');
  check('unavailableAudioExplained', await page.locator('.radio-error').innerText() === '音频暂时无法播放。请检查云盘分享，或打开洛雪收听。');
  await page.getByRole('button', { name: '网易云音乐', exact: true }).focus();
  await page.keyboard.press('Enter');
  check('keyboardModeAndAudioUnmount', await page.locator('audio').count() === 0 && await page.locator('iframe').count() === 1);
  await page.getByRole('button', { name: '考拉云盘', exact: true }).click();
  check('leavingNeteaseUnmountsIframe', await page.locator('iframe').count() === 0);
  await page.unroute('**/music/catalog.json');
  await page.getByRole('button', { name: '刷新目录', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('audio'));
  await page.getByRole('button', { name: '网易云音乐', exact: true }).click();
  await page.waitForSelector('iframe');
  await page.locator('iframe').scrollIntoViewIfNeeded();
  await page.frameLocator('iframe').locator('body').waitFor({ state: 'visible', timeout: 15000 }).catch(() => {});
  const frame = page.locator('iframe');
  check('sharedPlaylist', (await frame.getAttribute('src')).includes('id=18476425375') && (await frame.getAttribute('src')).includes('auto=0'));
  check('modeUrl', page.url().includes('mode=netease'));
  await page.screenshot({ path: path.join(root, 'netease-desktop.png'), fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  check('modeReload', await page.getByRole('button', { name: '网易云音乐', exact: true }).getAttribute('aria-pressed') === 'true');
  await page.getByRole('button', { name: '考拉云盘', exact: true }).click();
  await page.goBack();
  check('modeBack', await page.getByRole('button', { name: '网易云音乐', exact: true }).getAttribute('aria-pressed') === 'true');
  try {
    const external = page.frames().find(f => f.url().includes('outchain/player'));
    report.netease = external ? { url: external.url(), text: (await external.locator('body').innerText()).slice(0, 1400) } : { loaded: false };
  } catch (error) { report.netease = { error: error.message }; }
  await page.getByRole('button', { name: '考拉云盘', exact: true }).click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    check(`mobile${width}`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(root, `mobile-${width}.png`), fullPage: true });
  }
  await page.getByRole('button', { name: '网易云音乐', exact: true }).click();
  check('netease320Overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(root, 'netease-mobile.png'), fullPage: true });
  const nojs = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  await nojs.goto('http://127.0.0.1:4321/personal-homepage/music/');
  check('noJsFallback', await nojs.locator('.radio-track').count() === 18 && await nojs.locator('.radio-nojs a').isVisible());
  report.externalErrors = report.errors.filter(message => message.includes('device__browser_update') && message.includes('https://music.163.com'));
  const localErrors = report.errors.filter(message => !report.externalErrors.includes(message));
  check('noLocalPageErrors', localErrors.length === 0, localErrors);
  await browser.close();
  fs.writeFileSync(path.join(root, 'checks.json'), JSON.stringify(report, null, 2));
  if (report.checks.some(check => !check.passed)) process.exitCode = 1;
})().catch(error => { report.failure = error.message; fs.writeFileSync(path.join(root, 'checks.json'), JSON.stringify(report, null, 2)); console.error(error.message); process.exit(1); });
